// Njordlinger Combat Gameplay Overhaul - guild and faction routes by class (PLAN.md D30, GUILD-LOCKS.md; config/guild-routes.json).
//
// For each route's joining topic: an override of the topic header holding ONE new response (no vanilla response is
// overridden), placed first in the topic, with the topic's own first response's conditions (the speaker, the stage) plus
// "the class lacks the route's group" (our group global == 0) and "routes on" (NJCGO_RoutesOn == 1, kept by the SKSE
// plugin). While those hold, the refusal is spoken in place of the offer; otherwise the game's own response runs.
// The Dark Brotherhood's route is the SKSE plugin's (DB02 stopped as it starts). Built after every other record.
using System.Text.Json;
using System.Text.Json.Nodes;
using Mutagen.Bethesda;
using Mutagen.Bethesda.Plugins;
using Mutagen.Bethesda.Plugins.Records;
using Mutagen.Bethesda.Skyrim;
using Noggog;

static class GuildBuild
{
    public static void Run(SkyrimMod mod, ModKey modKey, string repo, JsonNode cfg, JsonObject forms)
    {
        var folders = (Environment.GetEnvironmentVariable("NJCGO_MASTERS") ?? "").Split(';', StringSplitOptions.RemoveEmptyEntries);
        var masters = new List<ISkyrimModGetter>();
        foreach (var m in new[] { "Skyrim.esm", "Update.esm", "Dawnguard.esm", "Dragonborn.esm" })
        {
            var path = folders.Select(f => Path.Combine(f, m)).FirstOrDefault(File.Exists);
            if (path != null) { masters.Add(SkyrimMod.CreateFromBinaryOverlay(path, SkyrimRelease.SkyrimSE)); }
        }
        T ByEdid<T>(string edid) where T : class, IMajorRecordGetter
        {
            foreach (var m in Enumerable.Reverse(masters)) { foreach (var r in m.EnumerateMajorRecords<T>()) { if (r.EditorID == edid) { return r; } } }
            throw new InvalidOperationException($"guild routes: {typeof(T).Name} {edid} is not in the masters");
        }
        string Ref(IMajorRecordGetter r) => r.FormKey.ModKey == modKey ? $"0x{r.FormKey.ID:X3}" : $"{r.FormKey.ModKey.FileName}|0x{r.FormKey.ID:X}";

        var routesOn = new GlobalShort(mod) { EditorID = "NJCGO_RoutesOn", Data = 1 };
        mod.Globals.Add(routesOn);
        var groupGlobals = forms["groupGlobals"]!.AsObject();
        var outRoutes = new JsonArray();
        foreach (var r in cfg["routes"]!.AsArray())
        {
            var id = r!["id"]!.GetValue<string>();
            var group = r["group"]!.GetValue<string>();
            var o = new JsonObject { ["id"] = id, ["name"] = r["name"]!.GetValue<string>(), ["group"] = group };
            if (r["stopQuest"] is JsonNode sq) { o["stopQuest"] = Ref(ByEdid<IQuestGetter>(sq.GetValue<string>())); }
            var infos = new JsonArray();
            foreach (var t in r["topics"]?.AsArray() ?? new JsonArray())
            {
                var src = ByEdid<IDialogTopicGetter>(t!.GetValue<string>());
                var first = src.Responses.FirstOrDefault() ?? throw new InvalidOperationException($"guild routes: {src.EditorID} has no response");
                var topic = mod.DialogTopics.GetOrAddAsOverride(src);
                topic.Responses.Clear();   // the override carries only our response; the game's own stay untouched
                var info = new DialogResponses(mod.GetNextFormKey(), SkyrimRelease.SkyrimSE)
                {
                    Flags = new DialogResponseFlags(),
                    FavorLevel = FavorLevel.None,
                };
                info.Responses.Add(new DialogResponse { Text = r["refusal"]!.GetValue<string>(), ResponseNumber = 1, Emotion = Emotion.Neutral, EmotionValue = 50 });
                foreach (var c in first.Conditions) { info.Conditions.Add(c.DeepCopy()); }
                var lacks = new GetGlobalValueConditionData();
                lacks.Global.Link.SetTo(new FormKey(modKey, Convert.ToUInt32(groupGlobals[group]!.GetValue<string>(), 16)));
                info.Conditions.Add(new ConditionFloat { CompareOperator = CompareOperator.EqualTo, ComparisonValue = 0, Data = lacks });
                var on = new GetGlobalValueConditionData();
                on.Global.Link.SetTo(routesOn.FormKey);
                info.Conditions.Add(new ConditionFloat { CompareOperator = CompareOperator.EqualTo, ComparisonValue = 1, Data = on });
                topic.Responses.Add(info);   // no previous response: the game places it first
                infos.Add(new JsonObject { ["topic"] = src.EditorID, ["topicForm"] = Ref(src), ["info"] = $"0x{info.FormKey.ID:X3}", ["copiedConditions"] = first.Conditions.Count });
            }
            o["refusals"] = infos;
            outRoutes.Add(o);
        }
        var table = new JsonObject
        {
            ["schema"] = "NjordlingerCGO guild routes 1",
            ["note"] = "GENERATED by tools/PluginBuild from config/guild-routes.json - do not edit",
            ["routesOnGlobal"] = $"0x{routesOn.FormKey.ID:X3}",
            ["routes"] = outRoutes
        };
        var outDir = Path.Combine(repo, "data", "SKSE", "Plugins", "NjordlingerCombatGameplayOverhaul");
        File.WriteAllText(Path.Combine(outDir, "guild-routes.json"), table.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + "\n");
        Console.WriteLine($"guild routes: {outRoutes.Count} routes, {outRoutes.Sum(x => x!["refusals"]!.AsArray().Count)} refusal responses");
    }
}
