r"""Generate config/quest-rewards.json from the quest records (PLAN.md D7, phase 2 step 7).

  py -3 tools\quest-rows.py --data "<game Data folder>" [--default 1]

Reads Skyrim.esm and Dragonborn.esm (read only) and writes one row per quest the main quest line and the Miraak line
are made of: every QUST whose type (DNAM) is Main Quest in Skyrim.esm, and every DLC2MQ* quest in Dragonborn.esm. Each
row pays --default points (D7: "a default per quest"); other Dragonborn quests are not listed, so they pay nothing.
The quest's shown name is read by the DLL from the running game; the file names quests by editor ID only.
"""
import argparse, json, os, re, struct, sys, zlib

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def records(buf, want=b"QUST"):
    """Yield (form id, flags, data) of every top-level record of type `want`, walking the GRUPs."""
    pos = 0
    n = len(buf)
    while pos + 24 <= n:
        typ = buf[pos:pos + 4]
        size = struct.unpack_from("<I", buf, pos + 4)[0]
        if typ == b"GRUP":
            label = buf[pos + 8:pos + 12]
            gtype = struct.unpack_from("<i", buf, pos + 12)[0]
            if gtype == 0 and label != want:
                pos += size
                continue
            pos += 24
            continue
        flags, fid = struct.unpack_from("<II", buf, pos + 8)
        data = buf[pos + 24:pos + 24 + size]
        if typ == want:
            if flags & 0x00040000:
                data = zlib.decompress(data[4:])
            yield fid, flags, data
        pos += 24 + size


def subrecords(data):
    pos = 0
    while pos + 6 <= len(data):
        typ = data[pos:pos + 4]
        size = struct.unpack_from("<H", data, pos + 4)[0]
        yield typ, data[pos + 6:pos + 6 + size]
        pos += 6 + size


def quests(path):
    buf = open(path, "rb").read()
    for fid, _, data in records(buf):
        edid, qtype = None, None
        for typ, payload in subrecords(data):
            if typ == b"EDID":
                edid = payload.split(b"\0", 1)[0].decode("cp1252", "replace")
            elif typ == b"DNAM" and len(payload) >= 12 and qtype is None:
                qtype = struct.unpack_from("<I", payload, 8)[0]
        if edid:
            yield edid, qtype, fid


def main(argv):
    p = argparse.ArgumentParser()
    p.add_argument("--data", required=True)
    p.add_argument("--dragonborn", help="Dragonborn.esm when it is not in --data (an MO2 mod folder)")
    p.add_argument("--default", type=int, default=1)
    a = p.parse_args(argv)
    rows = []
    for edid, qtype, fid in quests(os.path.join(a.data, "Skyrim.esm")):
        # the journal quests of the main line: type Main Quest and named MQ + three digits (the same type is carried
        # by helper and dialogue quests - MQ101DragonAttack, CWDialogueSoldiers - which never complete as a quest)
        if qtype == 1 and re.fullmatch(r"MQ\d{3}", edid):
            rows.append({"quest": edid, "line": "main quest", "points": a.default})
    dlc2 = a.dragonborn or os.path.join(a.data, "Dragonborn.esm")
    if os.path.exists(dlc2):
        for edid, qtype, fid in quests(dlc2):
            if re.fullmatch(r"DLC2MQ\d{2}", edid, re.IGNORECASE):
                rows.append({"quest": edid, "line": "Miraak", "points": a.default})
    out = {
        "_comment": "PLAN.md D7: perk points for the main quest and the Miraak line, generated by tools/quest-rows.py from "
                    "the quest records (main-quest type in Skyrim.esm, DLC2MQ* in Dragonborn.esm). points = what a "
                    "completion pays, once per save; default = a row without points. Change a row on the Quest Rewards "
                    "tab (kept in the INI) or here and rebuild.",
        "default": a.default,
        "rows": sorted(rows, key=lambda r: (r["line"] != "main quest", r["quest"])),
    }
    path = os.path.join(REPO, "config", "quest-rewards.json")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, indent=2)
        f.write("\n")
    print(f"wrote {os.path.relpath(path, REPO)}: {len(rows)} rows")
    for r in out["rows"]:
        print("  ", r["line"], r["quest"])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
