"""The class-dependent skills ring (the owner 04:42, PLAN.md D32): a tree the class does not hold is ABSENT from the ring -
no slot, no constellation, no name. Every class lineage holds a fixed set of trees (its groups, plus extra skills inherited
along the lineage); this script enumerates those sets from config/classes.json, writes one sky batch entry per set (the sky
must have exactly as many slots as trees, each slot showing its own tree's constellation) and the variants table the SKSE
plugin reads to write SKILLS.json for the current class.

Outputs (Test-only, under testonly/CustomSkillsRing):
  SKSE/Plugins/NjordlingerCombatGameplayOverhaul/ring-variants.json  - the variants and the full skill definitions
  generated/ring-sky-batch.json (repo)                               - for tools/make-skydome.py --batch
usage: py -3 tools/make-ring-variants.py   (after tools/make-skills-ring.py, which writes the full 20-tree SKILLS.json)
"""
import json
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RING = os.path.join(REPO, "testonly", "CustomSkillsRing")
# the game's own tree order = the vanilla sky's cImage index; CSF names; our classes.json skill names
ORDER = [("Enchanting", "Enchanting"), ("Smithing", "Smithing"), ("HeavyArmor", "HeavyArmor"), ("Block", "Block"), ("TwoHanded", "TwoHanded"),
         ("OneHanded", "OneHanded"), ("Marksman", "Archery"), ("LightArmor", "LightArmor"), ("Sneak", "Sneak"), ("Lockpicking", "Lockpicking"),
         ("Pickpocket", "Pickpocket"), ("Speechcraft", "Speech"), ("Alchemy", "Alchemy"), ("Illusion", "Illusion"), ("Conjuration", "Conjuration"),
         ("Destruction", "Destruction"), ("Restoration", "Restoration"), ("Alteration", "Alteration")]


def main():
    cfg = json.load(open(os.path.join(REPO, "config", "classes.json"), encoding="utf-8"))
    groups = cfg["groups"]
    classes = {c["id"]: c for c in cfg["classes"]}
    custom = {t["skill"]: t["group"] for t in cfg.get("customTrees", [])}   # Necromancer -> magic

    def held(lineage):
        cur = classes[lineage[-1]]
        out = set()
        for g in cur.get("groups", []):
            out |= set(groups[g])
        for cid in lineage:
            out |= set(classes[cid].get("extraSkills") or [])
        return out, set(cur.get("groups", []))

    lineages = []

    def walk(path):
        lineages.append(list(path))
        for n in classes[path[-1]].get("next") or []:
            if n in classes and n not in path:
                walk(path + [n])

    for c in cfg["classes"]:
        if c.get("start"):
            walk([c["id"]])

    full = json.load(open(os.path.join(RING, "SKSE", "Plugins", "CustomSkills", "SKILLS.json"), encoding="utf-8"))
    customDefs = {s["id"]: s for s in full["skills"] if isinstance(s, dict)}
    variants = {}

    def add(sk, grp, why):
        ring, cmap = [], []
        for i, (csf, ours) in enumerate(ORDER):
            if sk is None or ours in sk:
                ring.append(csf)
                cmap.append(str(i))
        ring.append("diving")
        cmap.append("diving")
        if grp is None or custom.get("Necromancer", "magic") in grp:
            ring.append("Necromancer")
            cmap.append("necromancer")
        key = ",".join(ring)
        if key not in variants:
            mask = "".join("1" if (sk is None or o in sk) else "0" for _, o in ORDER) + "1" + ("1" if "Necromancer" in ring else "0")
            variants[key] = {"id": f"ring_{int(mask, 2):05x}", "ring": ring, "map": cmap, "examples": []}
        variants[key]["examples"].append(why)

    add(None, None, "no class chosen")
    for lin in lineages:
        sk, grp = held(lin)
        add(sk, grp, " > ".join(lin))
    out = []
    batch = []
    for v in variants.values():
        sky = f"Interface/NjordlingerCGO/{v['id']}.nif"
        out.append({"id": v["id"], "ring": v["ring"], "sky": sky, "trees": len(v["ring"]), "examples": v["examples"]})
        batch.append({"out": os.path.join(RING, "meshes", "interface", "NjordlingerCGO", v["id"] + ".nif"), "map": v["map"]})
    table = {"note": "GENERATED by tools/make-ring-variants.py from config/classes.json (PLAN.md D32): one ring per held tree set; the SKSE plugin writes SKILLS.json from the variant of the current class",
             "skydomeCameraRightPoint": 1, "skills": customDefs, "variants": out}
    p = os.path.join(RING, "SKSE", "Plugins", "NjordlingerCombatGameplayOverhaul", "ring-variants.json")
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        json.dump(table, f, indent=2, ensure_ascii=False)
        f.write("\n")
    bp = os.path.join(REPO, "generated", "ring-sky-batch.json")
    with open(bp, "w", encoding="utf-8", newline="\n") as f:
        json.dump(batch, f, indent=2)
        f.write("\n")
    print(f"{len(out)} ring variants from {len(lineages)} lineages:")
    for v in out:
        print(f"  {v['id']}: {v['trees']} trees - {', '.join(v['examples'][:3])}{' ...' if len(v['examples']) > 3 else ''}")


if __name__ == "__main__":
    main()
