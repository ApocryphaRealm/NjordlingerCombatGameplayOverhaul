"""Convert a Custom Skills Framework JSON tree (SKSE/Plugins/CustomSkills/<key>.json, the newer format) into the
NetScriptFramework/Plugins/CustomSkill.<key>.config.txt that Custom Skills Framework 2.0.2 on 1.5.97 reads (combined run
efc8: Stormcrown ships only the JSON, so its Meditate does not open the Dragonborn tree on that framework).

The IDs are written as the JSON gives them (the plugin's own local IDs). A plugin flagged light (ESL) keeps those IDs when
the flag is cleared; whether the old framework needs the flag cleared is the installer's call (the Necromancer tree's
installer cleared it) - this script only writes the text.

usage: py -3 tools/csf-json-to-txt.py <in.json> <out.config.txt>
"""
import json
import sys


def split_ref(ref):
    if not ref:
        return "", "0"
    plugin, local = ref.split("|", 1)
    return plugin, "0x" + local.upper().lstrip("0X").rjust(3, "0") if not local.lower().startswith("0x") else local


def main(src, dst):
    j = json.load(open(src, encoding="utf-8"))
    sk = j["skills"][0]
    out = ["# Encoded : UTF-8", "# GENERATED by tools/csf-json-to-txt.py from " + src.replace("\\", "/").split("/")[-1] + " - do not edit", ""]

    def field(name, value):
        out.append(f'{name} = "{value}"' if isinstance(value, str) else f"{name} = {value}")

    def glob(name, ref):
        plugin, local = split_ref(ref)
        out.append(f'{name}File = "{plugin}"')
        out.append(f"{name}Id = {local}")

    field("Name", sk.get("name") or sk["id"])
    field("Description", sk.get("description") or "")
    field("Skydome", (j.get("skydome") or {}).get("model", ""))
    out.append("SkydomeNormalNif = False")
    glob("Level", sk.get("level"))
    glob("Ratio", sk.get("ratio"))
    glob("PerkPoints", j.get("perkPoints"))
    glob("ShowLevelup", sk.get("showLevelup"))
    glob("ShowMenu", j.get("showMenu"))
    glob("Legendary", sk.get("legendary"))
    glob("Color", sk.get("color"))
    glob("DebugReload", j.get("debugReload"))
    nodes = sk["nodes"]
    index = {n["id"]: i + 1 for i, n in enumerate(nodes)}
    linked = {l for n in nodes for l in n.get("links", [])}
    roots = [str(index[n["id"]]) for n in nodes if n["id"] not in linked]
    out += ["", "Node0.Enable = true", f'Node0.Links = "{" ".join(roots)}"', ""]
    for i, n in enumerate(nodes, 1):
        plugin, local = split_ref(n["perk"])
        gx, gy = round(n.get("x", 0.0)), round(n.get("y", 0.0))
        out += [f"# {i} : {n['id']}", f"Node{i}.Enable = true", f'Node{i}.PerkFile = "{plugin}"', f"Node{i}.PerkId = {local}",
                f"Node{i}.X = {n.get('x', 0.0) - gx:.2f}", f"Node{i}.Y = {n.get('y', 0.0) - gy:.2f}", f"Node{i}.GridX = {gx}", f"Node{i}.GridY = {gy}",
                f'Node{i}.Links = "{" ".join(str(index[l]) for l in n.get("links", []))}"', ""]
    with open(dst, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(out))
    print(f"{dst}: {len(nodes)} nodes, roots {roots}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
