r"""Write the reserved keyword scheme for soul stones and the slot table (PLAN.md phase 1 step 4) from WORD-TABLE.md.

  py -3 -I make-stone-scheme.py <WORD-TABLE.md> <out .json>

Phase 1 reserves the names; nothing in the game reads them before phase 4 (the DLL reads this file then). The words and
their shouts come from the word table's section headings ("## n. Fus Ro Dah - Unrelenting Force (visual: ...)"), so the
scheme follows the table when a shout is renamed. Exit 0 written, 1 the table has not 60 words in 20 shouts.
"""
import json, re, sys


def main(argv):
    if len(argv) != 2:
        print(__doc__)
        return 1
    table, out = argv
    shouts = []
    for line in open(table, encoding="utf-8"):
        m = re.match(r"^## (\d+)\. ([A-Za-z']+) ([A-Za-z']+) ([A-Za-z']+) - (.+?) \(visual: (.+)\)\s*$", line)
        if m:
            shouts.append({"index": int(m.group(1)), "words": [m.group(2), m.group(3), m.group(4)],
                           "shout": m.group(5), "visual": m.group(6)})
    words = [w for s in shouts for w in s["words"]]
    if len(shouts) != 20 or len(words) != 60 or len(set(words)) != 60:
        print("refused: expected 20 shouts of 3 distinct words, found %d shouts / %d words" % (len(shouts), len(words)))
        return 1
    stone_tiers = ["Petty", "Lesser", "Common", "Greater", "Grand"]
    scheme = {
        "schema": "NjordlingerCGO stone scheme 1",
        "source": "4. plans/njordlinger-combat-gameplay-overhaul/WORD-TABLE.md (generated by tools/make-stone-scheme.py)",
        "note": "Reserved in phase 1; read by the DLL from phase 4. Keywords are created by KID/the plugin when first used.",
        "itemTierKeywords": {t: "NJCGO_Tier_" + t for t in ["Common", "Magic", "Epic", "Legendary", "Unique"]},
        # D13: the tier's only bonus is the stone slot count; Q44 default: a unique has three plus its own effect
        "slotsByItemTier": {"Common": 0, "Magic": 1, "Epic": 2, "Legendary": 3, "Unique": 3},
        "stoneFamilyKeyword": "NJCGO_Stone",
        "stoneTiers": [{"tier": t, "keyword": "NJCGO_StoneTier_" + t, "soulGemColour": t} for t in stone_tiers],
        "words": [{"word": w, "keyword": "NJCGO_StoneWord_" + re.sub(r"[^A-Za-z]", "", w), "shout": s["shout"],
                   "shoutIndex": s["index"], "position": i + 1}
                  for s in shouts for i, w in enumerate(s["words"])],
        "shouts": shouts,
        # D15: uniques cannot be enchanted; D18: staves take no stones
        "noEnchantKeyword": "NJCGO_NoEnchant",
        "noStonesKeyword": "NJCGO_NoStones",
        "setKeywordPrefix": "NJCGO_Set_",
        "hosts": ["Melee", "Ranged", "Armour"],
    }
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        json.dump(scheme, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print("wrote %s: %d shouts, %d words, %d stone tiers" % (out, len(shouts), len(words), len(stone_tiers)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
